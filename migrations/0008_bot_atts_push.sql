CREATE TABLE IF NOT EXISTS bot_atts (
  id TEXT PRIMARY KEY, ref TEXT NOT NULL, bot TEXT NOT NULL, dir TEXT NOT NULL, env TEXT NOT NULL, size INTEGER NOT NULL, ts INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_bot_atts_ref ON bot_atts(ref, dir);
CREATE TABLE IF NOT EXISTS push_subs (
  endpoint TEXT PRIMARY KEY, p256dh TEXT NOT NULL, auth TEXT NOT NULL, created INTEGER NOT NULL
);
